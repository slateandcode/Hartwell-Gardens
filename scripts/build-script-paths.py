"""
Shape words in Pinyon Script with HarfBuzz and write each glyph outline as an
SVG path, so the hero's "Landscaping" and the "James Hartwell" signature can be
drawn on with DrawSVG instead of fading in as live text.

Usage: python scripts/build-script-paths.py <PinyonScript-Regular.ttf>
Writes lib/script-paths.ts. Coordinates are font units (1000/em), y down,
baseline at y=0.
"""
import json
import os
import sys

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

FONT = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), "..", "lib", "script-paths.ts")

# Figma: Pinyon Script, letter-spacing -1.5%
TRACKING = -0.015

tt = TTFont(FONT)
upm = tt["head"].unitsPerEm
scale = 1000 / upm
glyphset = tt.getGlyphSet()
order = tt.getGlyphOrder()
ascent = tt["hhea"].ascent * scale
descent = -tt["hhea"].descent * scale

blob = hb.Blob.from_file_path(FONT)
face = hb.Face(blob)
font = hb.Font(face)


def shape(text):
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True, "calt": True})
    glyphs = []
    x = 0.0
    xmin = ymin = float("inf")
    xmax = ymax = float("-inf")
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        gx = x + pos.x_offset * scale
        gy = -pos.y_offset * scale
        pen = SVGPathPen(glyphset, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        # flip y so the path reads top-down like the DOM
        tpen = TransformPen(pen, (scale, 0, 0, -scale, gx, gy))
        glyphset[name].draw(tpen)
        bpen = BoundsPen(glyphset)
        glyphset[name].draw(TransformPen(bpen, (scale, 0, 0, -scale, gx, gy)))
        if bpen.bounds:
            a, b, c, d = bpen.bounds
            xmin, ymin, xmax, ymax = min(xmin, a), min(ymin, b), max(xmax, c), max(ymax, d)
        d = pen.getCommands()
        if d:
            glyphs.append(d)
        x += pos.x_advance * scale + TRACKING * 1000
    advance = x - TRACKING * 1000
    return {
        "text": text,
        "advance": round(advance, 1),
        "ascent": round(ascent, 1),
        "descent": round(descent, 1),
        "bounds": [round(v, 1) for v in (xmin, ymin, xmax, ymax)],
        "glyphs": glyphs,
    }


data = {"landscaping": shape("Landscaping"), "signature": shape("James Hartwell")}

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/build-script-paths.py. Do not edit by hand.\n")
    fh.write("export type ScriptWord = {\n  text: string\n  advance: number\n  ascent: number\n  descent: number\n  bounds: [number, number, number, number]\n  glyphs: string[]\n}\n\n")
    for key, word in data.items():
        fh.write(f"export const {key}: ScriptWord = {json.dumps(word, indent=2)}\n\n")

for key, word in data.items():
    print(key, "advance", word["advance"], "bounds", word["bounds"], "glyphs", len(word["glyphs"]), "asc/desc", word["ascent"], word["descent"])
